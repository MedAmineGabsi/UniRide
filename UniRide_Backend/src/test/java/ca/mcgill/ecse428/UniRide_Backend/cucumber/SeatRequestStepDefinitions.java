/**
 * Step definitions for ID05 Request For Seat. The Background steps (current date, drivers,
 * passengers, rides) are also used by ID04 Search For Rides.
 */
public class SeatRequestStepDefinitions {

    private static final String SEAT_REQUESTS_URL = "/seat-requests";

    /** The feature files have no duration column. */
    private static final int DEFAULT_DURATION_MINUTES = 60;

    /** Owner of the accepted seat requests that make up each ride's accepted_seats. */
    private static final String OTHER_PASSENGER_EMAIL = "accepted.seats@mail.mcgill.ca";

    @Autowired
    private WebApplicationContext context;
    @Autowired
    private JdbcTemplate jdbcTemplate;
    @Autowired
    private PersonRepository personRepository;
    @Autowired
    private PersonRoleRepository personRoleRepository;
    @Autowired
    private PersonRoleAssignmentRepository assignmentRepository;
    @Autowired
    private DriverRepository driverRepository;
    @Autowired
    private PassengerRepository passengerRepository;
    @Autowired
    private RideRepository rideRepository;
    @Autowired
    private SeatRequestRepository seatRequestRepository;
    @Autowired
    private TestClock testClock;
    @Autowired
    private LastResponse lastResponse;

    private MockMvc mockMvc;

    /** Feature file ride_id -> id generated by the database. */
    private final Map<Integer, Integer> rideIds = new HashMap<>();

    private Passenger otherPassenger;
    private int nextStudentId = 260800000;
    private long seatRequestCountBefore;

    // ------------------------------------------------------------------ hooks

    @Before
    public void setUp() {
        jdbcTemplate.execute("TRUNCATE TABLE seat_request, ride, person_role_assignment, driver, passenger, "
                + "person_role, person RESTART IDENTITY CASCADE");
        mockMvc = MockMvcBuilders.webAppContextSetup(context).apply(springSecurity()).build();
    }

    @After
    public void resetClock() {
        testClock.reset();
    }

    // ------------------------------------------------------------------ Background

    /** "Now" becomes the start of that day in Montréal, so every ride later that day is still ahead. */
    @Given("the current date is {string}")
    public void theCurrentDateIs(String date) {
        testClock.setTo(LocalDate.parse(date).atStartOfDay());
    }

    @Given("the following drivers exist:")
    public void theFollowingDriversExist(DataTable drivers) {
        for (Map<String, String> row : drivers.asMaps()) {
            Person person = savePerson(row.get("email"), studentIdIn(row), row.get("firstName"), row.get("lastName"));
            assign(person, new Driver(row.get("licenseNumber")));
        }
    }

    @Given("the following passengers exist:")
    public void theFollowingPassengersExist(DataTable passengers) {
        for (Map<String, String> row : passengers.asMaps()) {
            Person person = savePerson(row.get("email"), studentIdIn(row), row.get("firstName"), row.get("lastName"));
            assign(person, new Passenger());
        }
    }

    /**
     * Rides are saved directly, without the ride creation rules, so the tables can use short
     * places like "Montreal". accepted_seats becomes one ACCEPTED request from another passenger.
     */
    @Given("the following rides exist:")
    public void theFollowingRidesExist(DataTable rides) {
        for (Map<String, String> row : rides.asMaps()) {
            Driver driver = driverRepository.findByPersonEmail(row.get("driver"))
                    .orElseThrow(() -> new IllegalStateException("No driver with email " + row.get("driver")));
            Ride ride = new Ride(driver, row.get("origin"), row.get("destination"),
                    LocalDateTime.parse(row.get("departure_date_time"), RideValidator.DEPARTURE_FORMAT),
                    DEFAULT_DURATION_MINUTES, Integer.parseInt(row.get("total_seats")),
                    new BigDecimal(row.get("price_per_seat")));
            ride.setStatus(RideStatus.valueOf(row.get("status").trim().toUpperCase(Locale.ROOT)));
            ride = rideRepository.save(ride);
            rideIds.put(Integer.valueOf(row.get("ride_id")), ride.getId());

            String acceptedSeats = row.get("accepted_seats");
            int accepted = acceptedSeats == null || acceptedSeats.isBlank() ? 0 : Integer.parseInt(acceptedSeats);
            if (accepted > 0) {
                saveSeatRequest(otherPassenger(), ride, accepted, SeatRequestStatus.ACCEPTED);
            }
        }
    }

    // ------------------------------------------------------------------ ID05

    @Given("passenger {string} already has a seat request on ride {int} with status {string}")
    public void passengerAlreadyHasSeatRequest(String email, int rideId, String status) {
        Passenger passenger = passengerRepository.findByPersonEmail(email).orElseThrow();
        Ride ride = rideRepository.findById(databaseIdOf(rideId)).orElseThrow();
        saveSeatRequest(passenger, ride, 1, SeatRequestStatus.valueOf(status.trim().toUpperCase(Locale.ROOT)));
    }

    @When("passenger {string} requests {int} seats on ride {int}")
    public void passengerRequestsSeatsOnRide(String email, int seats, int rideId) throws Exception {
        seatRequestCountBefore = seatRequestRepository.count();
        lastResponse.set(mockMvc.perform(post(SEAT_REQUESTS_URL)
                .with(jwt().jwt(token -> token.claim("email", email)))
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"rideId\": " + databaseIdOf(rideId) + ", \"seatsRequested\": " + seats + "}"))
                .andReturn()
                .getResponse());
    }

    @Then("a seat request is created for passenger {string} on ride {int} for {int} seats with status {string}")
    public void seatRequestIsCreated(String email, int rideId, int seats, String status) throws Exception {
        MockHttpServletResponse response = lastResponse.get();
        assertEquals(HttpStatus.CREATED.value(), response.getStatus(), response.getContentAsString());
        Integer matching = jdbcTemplate.queryForObject("""
                SELECT count(*)
                FROM seat_request s
                JOIN person_role_assignment a ON a.role_id = s.passenger_id
                JOIN person p ON p.id = a.person_id
                WHERE lower(p.email) = lower(?) AND s.ride_id = ? AND s.seats_requested = ? AND s.status = ?
                """, Integer.class, email, databaseIdOf(rideId), seats, status.trim().toUpperCase(Locale.ROOT));
        assertEquals(1, matching, "Expected exactly one matching seat request");
    }

    @Then("no seat request is created")
    public void noSeatRequestIsCreated() throws Exception {
        assertNoSeatRequestCreated();
    }

    @Then("no additional seat request is created")
    public void noAdditionalSeatRequestIsCreated() throws Exception {
        assertNoSeatRequestCreated();
    }

    // ------------------------------------------------------------------ helpers

    private void assertNoSeatRequestCreated() throws Exception {
        MockHttpServletResponse response = lastResponse.get();
        assertNotEquals(HttpStatus.CREATED.value(), response.getStatus(), response.getContentAsString());
        assertEquals(seatRequestCountBefore, seatRequestRepository.count(), "No seat request should be saved");
    }

    /** Database id of a feature file ride; an unknown ride_id is sent as is, so it is not found. */
    private int databaseIdOf(int rideId) {
        return rideIds.getOrDefault(rideId, rideId);
    }

    private Person savePerson(String email, String studentId, String firstName, String lastName) {
        return personRepository.save(new Person(studentId, email, "test-password-hash", firstName, lastName, null));
    }

    private void assign(Person person, PersonRole role) {
        PersonRole saved = personRoleRepository.save(role);
        assignmentRepository.save(new PersonRoleAssignment(person, saved));
    }

    /** studentID or student_id column if the table has one, otherwise a unique generated id. */
    private String studentIdIn(Map<String, String> row) {
        String studentId = row.containsKey("studentID") ? row.get("studentID") : row.get("student_id");
        return studentId == null || studentId.isBlank() ? String.valueOf(nextStudentId++) : studentId;
    }

    private Passenger otherPassenger() {
        if (otherPassenger == null) {
            Person person = savePerson(OTHER_PASSENGER_EMAIL, String.valueOf(nextStudentId++), "Other", "Passenger");
            Passenger passenger = personRoleRepository.save(new Passenger());
            assignmentRepository.save(new PersonRoleAssignment(person, passenger));
            otherPassenger = passenger;
        }
        return otherPassenger;
    }

    private void saveSeatRequest(Passenger passenger, Ride ride, int seats, SeatRequestStatus status) {
        SeatRequest request = new SeatRequest(passenger, ride, seats);
        request.setStatus(status);
        seatRequestRepository.save(request);
    }
}
